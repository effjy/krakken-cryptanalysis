N = 8

def anf(f):
    """Mobius transform: truth table (len 256) -> set of monomial exponent masks."""
    a = f[:]
    for i in range(N):
        s = 1 << i
        for x in range(256):
            if x & s:
                a[x] ^= a[x ^ s]
    return {x for x in range(256) if a[x]}

def covers(w, u):
    return (u & ~w) == 0

def product_function_anf(v):
    f = [1] * 256
    for i in range(N):
        if (v >> i) & 1:
            for x in range(256):
                f[x] &= (ABYSSAL[x] >> i) & 1
    return anf(f)

def all_trails():
    reach = {u: set() for u in range(256)}
    for v in range(256):
        mons = product_function_anf(v)
        for u in range(256):
            if any(covers(w, u) for w in mons):
                reach[u].add(v)
    trails = {}
    for u in range(256):
        vs = reach[u]
        minimal = [v for v in vs if not any((v2 != v and (v2 & ~v) == 0) for v2 in vs)]
        trails[u] = sorted(minimal)
    return trails

